/**
 * fyd/tailwind-theme: DTCG -> Tailwind v4 @theme block.
 *
 * RENDER TARGET ONLY (token-model 8.1 step 5): @theme re-exports the
 * compiled custom properties as Tailwind utilities (bg-surface-brand,
 * text-text-primary, font-display). Tailwind never originates a value.
 * Primitive-tier colors are deliberately NOT re-exported: product code
 * references semantic/component tokens only, never primitives.
 *
 * Mapping (token path -> @theme variable):
 *   surface|text|brand|accent|action|border|status|focus|nav|trust-bar|
 *   hero|cta|service-card|footer|story . *  ->  --color-<kebab path>
 *   font.display.<theme>                    ->  --font-display
 *   font.body.<theme>                       ->  --font-body
 *   type.<step>                             ->  --text-<step>
 *   space.<n>                               ->  --spacing-<n>
 *   radius.<n>                              ->  --radius-<n>
 *   shadow.<n>                              ->  --shadow-<n>
 *   media.aspect.<n>                        ->  --aspect-<n>
 * Everything else (primitives, widths, motion, section rhythm) stays
 * CSS-variables-only.
 */
const HEADER = `/**
 * DO NOT EDIT. Generated by fyd-product-lane/builder/tokens/build.cjs
 * from DTCG 2025.10 sources. Tailwind v4 @theme render target.
 */`;

const COLOR_GROUPS = new Set([
  "surface",
  "text",
  "brand",
  "accent",
  "action",
  "border",
  "status",
  "focus",
  "nav",
  "trust-bar",
  "hero",
  "cta",
  "service-card",
  "footer",
  "story",
]);

function tailwindName(path, theme) {
  const [group, ...rest] = path;
  if (COLOR_GROUPS.has(group)) return `--color-${[group, ...rest].join("-")}`;
  if (group === "font" && rest[0] === "display" && rest[1] === theme) return "--font-display";
  if (group === "font" && rest[0] === "body" && rest[1] === theme) return "--font-body";
  if (group === "type" && rest.length === 1) return `--text-${rest[0]}`;
  if (group === "space" && rest.length === 1) return `--spacing-${rest[0]}`;
  if (group === "radius" && rest.length === 1) return `--radius-${rest[0]}`;
  if (group === "shadow" && rest.length === 1) return `--shadow-${rest[0]}`;
  if (group === "media" && rest[0] === "aspect" && rest.length === 2) return `--aspect-${rest[1]}`;
  return null;
}

export function registerTailwindThemeFormat(StyleDictionary) {
  StyleDictionary.registerFormat({
    name: "fyd/tailwind-theme",
    format: ({ dictionary, options }) => {
      const theme = options.theme ?? "unknown";
      const lines = [];
      for (const token of dictionary.allTokens) {
        const name = tailwindName(token.path, theme);
        if (name) lines.push(`  ${name}: var(--${token.name});`);
      }
      return `${HEADER}\n@theme inline {\n${lines.join("\n")}\n}\n`;
    },
  });
}

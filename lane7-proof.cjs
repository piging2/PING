#!/usr/bin/env node
// LANE 7: two-site browser verification (fresh Chrome on CDP 9224, never :9223).
// Runs ON THE PIG (Windows) via node.exe. Usage: node lane7-proof.cjs
// Output: JSON stages to stdout; screenshots to OUT_DIR.
const { chromium } = require('C:/Users/nolan/.local/share/pigi/fb-engage/node_modules/playwright-core');
const fs = require('fs');
const path = require('path');

const OUT_DIR = 'C:/Users/nolan/lane7-proof/shots';
const WSL_IP = '172.21.65.209';
const SITES = [
  { id: 'happy-place', port: 3103, path: '/sites/happy-place', askQ: 'What services does this business offer?', expectHeroMedia: false },
  { id: 'coppersmith-plumbing', port: 3104, path: '/sites/coppersmith-plumbing', askQ: 'What plumbing services do you offer?', expectHeroMedia: true },
];
const sleep = ms => new Promise(r => setTimeout(r, ms));
const results = { started: new Date().toISOString(), stages: [] };
function stage(name, ok, detail) {
  results.stages.push({ name, ok, detail: (detail || '').slice(0, 500), at: new Date().toISOString() });
  console.log(`STAGE ${ok ? 'PASS' : 'FAIL'} ${name}${detail ? ' :: ' + String(detail).slice(0, 200) : ''}`);
}
async function block(name, fn) {
  try { await fn(); }
  catch (e) { stage(name + ':block-error', false, String((e && e.message) || e).slice(0, 300)); }
}

(async () => {
  fs.mkdirSync(OUT_DIR, { recursive: true });
  const browser = await chromium.connectOverCDP('http://127.0.0.1:9224', { timeout: 30000 });
  const ctx = browser.contexts()[0];

  for (const site of SITES) {
    const tag = site.id;
    const bases = [`http://127.0.0.1:${site.port}`, `http://${WSL_IP}:${site.port}`];
    let BASE = null;
    for (const b of bases) {
      const p = await ctx.newPage();
      try {
        const r = await p.goto(b + site.path, { waitUntil: 'domcontentloaded', timeout: 20000 });
        if (r && r.ok()) { BASE = b; await p.close(); break; }
      } catch (e) { /* try next */ }
      await p.close();
    }
    stage(`${tag}:base-reachable`, !!BASE, BASE || 'no base reachable');
    if (!BASE) continue;

    // ---------- VIEW (desktop 1280) ----------
    await block(`${tag}:view`, async () => {
      const page = await ctx.newPage();
      await page.setViewportSize({ width: 1280, height: 800 });
      const consoleErrors = [];
      page.on('console', m => { if (m.type() === 'error') consoleErrors.push(m.text().slice(0, 200)); });
      page.on('pageerror', e => consoleErrors.push('PAGEERROR: ' + String(e.message || e).slice(0, 200)));
      const resp = await page.goto(BASE + site.path, { waitUntil: 'networkidle', timeout: 60000 });
      await sleep(1500);
      const info = await page.evaluate(() => ({
        title: document.title,
        h1: (document.querySelector('h1') || {}).innerText || '',
        imgCount: document.querySelectorAll('img').length,
        heroImg: !!document.querySelector('img[src*="fyd-media"]'),
        bgHero: [...document.querySelectorAll('*')].filter(el => {
          const s = getComputedStyle(el).backgroundImage || '';
          return s.includes('fyd-media');
        }).length,
        askInput: !!document.querySelector('#ask-fyd-question'),
        customize: document.body.innerText.includes('Customize this site'),
        whyThisCount: [...document.querySelectorAll('summary')].filter(s => /why this/i.test(s.textContent || '')).length,
        provenance: document.body.innerText.includes('Generated by FYD Social'),
      }));
      stage(`${tag}:view-status`, resp && resp.ok(), 'http=' + (resp && resp.status()));
      stage(`${tag}:view-title`, info.title.length > 3, info.title);
      const heroOk = site.expectHeroMedia ? (info.heroImg || info.bgHero > 0) : true;
      stage(`${tag}:view-hero-media`, heroOk, `fyd-media img=${info.heroImg} bgHero=${info.bgHero} imgs=${info.imgCount}`);
      stage(`${tag}:view-provenance`, info.provenance, info.h1.slice(0, 80));
      stage(`${tag}:view-console-clean`, consoleErrors.length === 0, consoleErrors.slice(0, 3).join(' ;; '));
      await page.screenshot({ path: path.join(OUT_DIR, `${tag}-desktop.png`) });
      await page.close();
    });

    // ---------- MOBILE (390px) ----------
    await block(`${tag}:mobile`, async () => {
      const page = await ctx.newPage();
      await page.setViewportSize({ width: 390, height: 844 });
      await page.goto(BASE + site.path, { waitUntil: 'networkidle', timeout: 60000 });
      await sleep(1500);
      const m = await page.evaluate(() => {
        const de = document.documentElement;
        const bad = [];
        for (const el of document.querySelectorAll('button, a, input, summary')) {
          const r = el.getBoundingClientRect();
          if (r.width === 0 && r.height === 0) continue;
          if (r.width < 44 || r.height < 44) bad.push(((el.innerText || el.getAttribute('aria-label') || el.id || el.tagName) + '').trim().slice(0, 30) + ` ${Math.round(r.width)}x${Math.round(r.height)}`);
          if (bad.length >= 10) break;
        }
        return { scrollW: de.scrollWidth, clientW: de.clientWidth, bad };
      });
      stage(`${tag}:mobile-no-overflow`, m.scrollW <= m.clientW + 1, `scrollW=${m.scrollW} clientW=${m.clientW}`);
      stage(`${tag}:mobile-touch-targets`, m.bad.length === 0, m.bad.slice(0, 6).join(' ;; ') || 'all >=44px');
      await page.screenshot({ path: path.join(OUT_DIR, `${tag}-mobile.png`) });
      await page.close();
    });

    // ---------- ASK FYD ----------
    await block(`${tag}:ask`, async () => {
      const page = await ctx.newPage();
      await page.setViewportSize({ width: 1280, height: 800 });
      await page.goto(BASE + site.path, { waitUntil: 'networkidle', timeout: 60000 });
      await sleep(1000);
      const input = page.locator('#ask-fyd-question');
      await input.scrollIntoViewIfNeeded();
      await input.fill(site.askQ);
      await page.screenshot({ path: path.join(OUT_DIR, `${tag}-ask-before.png`) });
      await input.press('Enter');
      let answered = false;
      const t0 = Date.now();
      while (Date.now() - t0 < 45000) {
        const st = await page.evaluate(() => document.body.innerText.slice(-4000));
        if (/why this\?/i.test(st)) { answered = true; break; }
        await sleep(1000);
      }
      const ans = await page.evaluate(() => {
        const body = document.body.innerText;
        const idx = body.toLowerCase().lastIndexOf('why this?');
        return {
          hasWhyThis: idx >= 0,
          tail: body.slice(Math.max(0, idx - 1500), idx + 200),
          sourceWord: /source/i.test(body.slice(Math.max(0, idx - 1500), idx)),
        };
      });
      stage(`${tag}:ask-answered`, answered, ans.tail.slice(0, 300).replace(/\n/g, ' '));
      stage(`${tag}:ask-why-this-disclosure`, ans.hasWhyThis, 'mentions source=' + ans.sourceWord);
      await page.screenshot({ path: path.join(OUT_DIR, `${tag}-ask-after.png`) });
      await page.close();
    });

    // ---------- WHY THIS (expand first VISIBLE disclosure) ----------
    await block(`${tag}:whythis`, async () => {
      const page = await ctx.newPage();
      await page.setViewportSize({ width: 1280, height: 800 });
      await page.goto(BASE + site.path, { waitUntil: 'networkidle', timeout: 60000 });
      await sleep(1000);
      const n = await page.evaluate(() =>
        [...document.querySelectorAll('summary')].filter(s => /why this/i.test(s.textContent || '') && s.offsetParent !== null).length);
      stage(`${tag}:whythis-present`, n > 0, 'visible count=' + n);
      if (n > 0) {
        const detail = await page.evaluate(() => {
          const s = [...document.querySelectorAll('summary')].find(x => /why this/i.test(x.textContent || '') && x.offsetParent !== null);
          if (!s) return '';
          s.scrollIntoView({ block: 'center' });
          s.click();
          const d = s.closest('details');
          return d ? d.innerText.slice(0, 600) : '';
        });
        await sleep(800);
        const okSteps = /source|evidence|observed|extract/i.test(detail);
        stage(`${tag}:whythis-steps`, okSteps, detail.slice(0, 250).replace(/\n/g, ' '));
        await page.screenshot({ path: path.join(OUT_DIR, `${tag}-whythis.png`) });
      }
      await page.close();
    });

    // ---------- CUSTOMIZE (structured editor renders) ----------
    await block(`${tag}:customize`, async () => {
      const page = await ctx.newPage();
      await page.setViewportSize({ width: 1280, height: 800 });
      await page.goto(BASE + site.path, { waitUntil: 'networkidle', timeout: 60000 });
      await sleep(1000);
      const h = page.locator('h2', { hasText: 'Customize this site' });
      await h.scrollIntoViewIfNeeded();
      const editorVisible = await h.count() > 0;
      const btnCount = await page.evaluate(() => [...document.querySelectorAll('button')].filter(b => /move|hide|show|feature|propose/i.test(b.innerText)).length);
      stage(`${tag}:customize-editor-renders`, editorVisible && btnCount > 0, 'editor buttons=' + btnCount);
      await page.screenshot({ path: path.join(OUT_DIR, `${tag}-customize.png`) });
      await page.close();
    });
  }

  console.log('RESULT_JSON_BEGIN');
  console.log(JSON.stringify(results, null, 2));
  await browser.close();
})().catch(e => { console.error('FATAL', e); process.exit(1); });

/**
 * Deployment parameters (P1/P2/P12/P13): values that vary per deployment,
 * never per tenant. These are read from the environment (or injected by the
 * caller) so the route files contain no deployment-specific values and no
 * tenant checks.
 */

/** P1: tenant identity validation. Fail-closed on a malformed id. */
const TENANT_ID_RE = /^[a-z0-9][a-z0-9-]{0,62}[a-z0-9]$/;

export function validateTenantId(tenantId: string): string {
  if (!TENANT_ID_RE.test(tenantId)) {
    throw new Error(
      `fyd-compose: invalid tenantId ${JSON.stringify(tenantId)}: provisioning defect, refusing to render`,
    );
  }
  return tenantId;
}

/** P2: chrome mode. Explicit, env-only, default customer. */
export type ChromeMode = "customer" | "demo";

export function resolveChromeMode(env: NodeJS.ProcessEnv = process.env): ChromeMode {
  return env.FYD_CHROME_MODE === "demo" ? "demo" : "customer";
}

/** P13: SEO brand name. Absent means the brand is omitted from metadata. */
export function resolveSeoBrandName(env: NodeJS.ProcessEnv = process.env): string | null {
  const v = (env.FYD_SEO_BRAND_NAME ?? "").trim();
  return v === "" ? null : v;
}

export function siteTitle(ownerName: string, brand: string | null): string {
  return brand ? `${ownerName} | ${brand}` : ownerName;
}

export function siteDescription(ownerName: string, brand: string | null): string {
  return brand
    ? `A procedurally generated site for ${ownerName}, compiled by ${brand} from its PING-backed object graph.`
    : `A procedurally generated site for ${ownerName} from its PING-backed object graph.`;
}

/**
 * P12: provenance footer sentence. The template is deployment copy with
 * slots {brand}, {ingestionMethod}, and {eventRange}. meta.eventSequences
 * renders as "65-83" (or "65" when start == end); when eventSequences is
 * missing, the event-range clause is omitted rather than printing a
 * placeholder. An empty template renders nothing (the footer stays empty
 * but present; fail-closed, never invented).
 */
export const DEFAULT_PROVENANCE_TEMPLATE =
  "Generated by {brand} from a {ingestionMethod} object graph (acceptance sequences {eventRange}). All claims on this page are website statements, never verified fact.";

export interface ProvenanceInputs {
  brand?: string | null;
  ingestionMethod?: string | null;
  eventSequences?: [number, number] | null;
  /** Deployment-provided template override; null/undefined uses the default. */
  template?: string | null;
}

export function renderProvenanceSentence(inputs: ProvenanceInputs): string | null {
  const template = inputs.template ?? DEFAULT_PROVENANCE_TEMPLATE;
  if (template.trim() === "") return null;
  const [start, end] = inputs.eventSequences ?? [];
  const range = start === undefined || end === undefined ? null : start === end ? `${start}` : `${start}-${end}`;
  let out = template;
  if (range === null) {
    // Omit the whole event-range clause, not just the slot.
    out = out.replace(" (acceptance sequences {eventRange})", "");
  }
  return out
    .replace("{brand}", inputs.brand ?? "FYD Social")
    .replace("{ingestionMethod}", inputs.ingestionMethod ?? "website-ingestion")
    .replace("{eventRange}", range ?? "");
}

/**
 * Deployment parameter tests (P1/P2/P12/P13): env-only values with
 * fail-closed defaults. Nothing here varies per tenant.
 */

import {
  DEFAULT_PROVENANCE_TEMPLATE,
  renderProvenanceSentence,
  resolveChromeMode,
  resolveSeoBrandName,
  siteDescription,
  siteTitle,
  validateTenantId,
} from "../params";

describe("validateTenantId (P1)", () => {
  test("accepts well-formed ids", () => {
    expect(validateTenantId("happy-place")).toBe("happy-place");
    expect(validateTenantId("a1")).toBe("a1");
  });

  test("rejects malformed ids: provisioning defect, refuse to render", () => {
    expect(() => validateTenantId("")).toThrow();
    expect(() => validateTenantId("Happy Place")).toThrow();
    expect(() => validateTenantId("../etc")).toThrow();
    expect(() => validateTenantId("-leading")).toThrow();
  });
});

describe("resolveChromeMode (P2)", () => {
  test("default is customer", () => {
    expect(resolveChromeMode({})).toBe("customer");
  });

  test("demo only on the explicit value", () => {
    expect(resolveChromeMode({ FYD_CHROME_MODE: "demo" })).toBe("demo");
    expect(resolveChromeMode({ FYD_CHROME_MODE: "Demo" })).toBe("customer");
    expect(resolveChromeMode({ FYD_CHROME_MODE: "true" })).toBe("customer");
  });
});

describe("renderProvenanceSentence (P12)", () => {
  test("B2 acceptance: [1,4] renders 'acceptance sequences 1-4'", () => {
    const s = renderProvenanceSentence({
      brand: "FYD Social",
      ingestionMethod: "website-ingestion",
      eventSequences: [1, 4],
    });
    expect(s).toContain("(acceptance sequences 1-4)");
  });

  test("B2 acceptance: null eventSequences omits the clause, no placeholder", () => {
    const s = renderProvenanceSentence({
      brand: "FYD Social",
      ingestionMethod: "website-ingestion",
      eventSequences: null,
    });
    expect(s).not.toContain("acceptance sequences");
    expect(s).not.toContain("{eventRange}");
  });

  test("equal start/end renders a single number", () => {
    const s = renderProvenanceSentence({ eventSequences: [65, 65] });
    expect(s).toContain("(acceptance sequences 65)");
  });

  test("the HPP footer sentence is reproduced byte-for-byte", () => {
    const s = renderProvenanceSentence({
      brand: "FYD Social",
      ingestionMethod: "website-ingestion",
      eventSequences: [65, 83],
    });
    expect(s).toBe(
      "Generated by FYD Social from a website-ingestion object graph " +
        "(acceptance sequences 65-83). All claims on this page are website " +
        "statements, never verified fact.",
    );
  });

  test("empty template renders nothing", () => {
    expect(renderProvenanceSentence({ template: "   " })).toBeNull();
  });

  test("deployment template override is honored", () => {
    const s = renderProvenanceSentence({
      template: "Built by {brand} via {ingestionMethod}.",
      brand: "Acme",
      ingestionMethod: "crawl",
    });
    expect(s).toBe("Built by Acme via crawl.");
  });

  test("default template is the documented seed", () => {
    expect(DEFAULT_PROVENANCE_TEMPLATE).toContain("{brand}");
    expect(DEFAULT_PROVENANCE_TEMPLATE).toContain("{ingestionMethod}");
    expect(DEFAULT_PROVENANCE_TEMPLATE).toContain("{eventRange}");
  });
});

describe("seo brand (P13)", () => {
  test("absent env means the brand is omitted", () => {
    expect(resolveSeoBrandName({})).toBeNull();
    expect(resolveSeoBrandName({ FYD_SEO_BRAND_NAME: "  " })).toBeNull();
  });

  test("present env is trimmed and used", () => {
    expect(resolveSeoBrandName({ FYD_SEO_BRAND_NAME: " FYD Social " })).toBe(
      "FYD Social",
    );
  });

  test("title and description templates", () => {
    expect(siteTitle("Acme Plumbing", "FYD Social")).toBe(
      "Acme Plumbing | FYD Social",
    );
    expect(siteTitle("Acme Plumbing", null)).toBe("Acme Plumbing");
    expect(siteDescription("Acme Plumbing", "FYD Social")).toBe(
      "A procedurally generated site for Acme Plumbing, compiled by FYD Social from its PING-backed object graph.",
    );
    expect(siteDescription("Acme Plumbing", null)).toBe(
      "A procedurally generated site for Acme Plumbing from its PING-backed object graph.",
    );
  });
});

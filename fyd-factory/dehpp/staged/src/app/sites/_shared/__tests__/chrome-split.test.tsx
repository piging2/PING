/**
 * B1 removal proof: the customer surface ships no demo chrome.
 *
 * With chromeMode == "customer" (the default), the rendered HTML contains
 * no FYD Social demo header, no validator banner markup, and no structured
 * editor DOM. The customer surface (tabs, page, provenance footer) is
 * intact. This is the test the B1 removal plan requires.
 */
import { renderToStaticMarkup } from "react-dom/server";
import { CustomerSite } from "../customer-site";
import { generateSiteSpec } from "@/fyd/proceduralize/generator";
import { HAPPY_PLACE_RICH_GRAPH } from "@/fyd/proceduralize/__fixtures__/happy-place-rich-graph";

const AT = "2026-09-21T12:00:00.000Z";

function customerHtml(): string {
  const spec = generateSiteSpec(HAPPY_PLACE_RICH_GRAPH, {
    generatedAt: AT,
    eventSequences: [1, 4],
  });
  return renderToStaticMarkup(
    CustomerSite({
      spec,
      graph: HAPPY_PLACE_RICH_GRAPH,
      renderable: true,
      siteId: "happy-place",
      objectMedia: {},
      // Custom deployment brand: any "FYD Social" left in the output would
      // be demo chrome leaking, not deployment copy.
      provenanceSentence:
        "Generated by Acme Deployments from a website-ingestion object graph (acceptance sequences 1-4).",
    }),
  );
}

describe("B1 chrome split", () => {
  test("customer mode renders no demo header", () => {
    const html = customerHtml();
    expect(html).not.toContain("Generated site demo");
    expect(html).not.toContain("FYD Social");
  });

  test("customer mode renders no validator banner or editor DOM", () => {
    const html = customerHtml();
    expect(html).not.toContain("Spec failed validation");
    expect(html).not.toContain("Validator notes");
    expect(html).not.toContain("EditorPanel");
    expect(html).not.toContain("structured editor");
  });

  test("customer surface stays intact: tabs, page content, provenance footer", () => {
    const html = customerHtml();
    // Page tabs from spec.navigation.
    expect(html).toContain("Services");
    // Provenance footer carries the deployment sentence with the tenant's
    // own event sequences (B2), not a hardcoded literal.
    expect(html).toContain("Acme Deployments");
    expect(html).toContain("(acceptance sequences 1-4)");
  });
});

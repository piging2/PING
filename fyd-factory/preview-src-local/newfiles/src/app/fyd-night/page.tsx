function cohortSiteIds(): string[] {
  const ids = (manifest as { siteIds?: unknown }).siteIds;
  return Array.isArray(ids) ? ids.filter((s): s is string => typeof s === "string") : [];
}

function Card({
  href,
  name,
  blurb,
  tag,
}: {
  href: string;
  name: string;
  blurb: string;
  tag: string;
}) {
  return (
    <Link
      href={href}
      className="block rounded-2xl border border-stone-200 bg-white p-5 transition hover:border-amber-600 hover:shadow-md focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-amber-700"
    >
      <p className="text-xs font-bold uppercase tracking-widest text-amber-800">{tag}</p>
      <h2 className="mt-2 text-xl font-bold text-stone-900">{name}</h2>
      <p className="mt-1 text-sm text-stone-600">{blurb}</p>
    </Link>
  );
}


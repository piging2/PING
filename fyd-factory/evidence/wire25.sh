#!/bin/bash
# Regenerate P-1 and P-2 patches against the CURRENT dirty worktree using git diff.
# This produces patches with correct line numbers and context for the live files.
cd /home/nolan/projects/ping || exit 1

echo "=== P-1: site-client.tsx ==="
cp src/app/sites/_shared/site-client.tsx /tmp/site-client-new.tsx
python3 << 'PYEOF'
path = "/tmp/site-client-new.tsx"
src = open(path).read()

# 1. Insert provenanceSentence after the VIEWER line
anchor = 'const VIEWER: ViewerContext = { viewerId: null, displayName: null };\n'
assert src.count(anchor) == 1, "VIEWER anchor not unique"
func = '''
/**
 * Provenance footer sentence, rendered from spec.provenance (QA-TRUTH F-001).
 * The acceptance-sequence parenthetical appears only when the spec carries
 * an eventSequences pair; it is never hardcoded. Fail closed on display:
 * absent provenance data omits the parenthetical rather than printing a
 * placeholder or a wrong number.
 */
function provenanceSentence(spec: FYDSiteSpec): string {
  const provenance = spec.provenance;
  const seq = provenance?.eventSequences;
  const seqText =
    Array.isArray(seq) && seq.length === 2
      ? ` (acceptance sequences ${seq[0]}-${seq[1]})`
      : "";
  const source = provenance?.source ?? "website-ingestion";
  return (
    `Generated by FYD Social from a ${source} object graph${seqText}. ` +
    "All claims on this page are website statements, never verified fact."
  );
}
'''
src = src.replace(anchor, anchor + func, 1)

# 2. Replace the hardcoded footer paragraph
old_footer = """          <p>
            Generated by FYD Social from a website-ingestion object graph
            (acceptance sequences 65-83). All claims on this page are website
            statements, never verified fact.
          </p>"""
new_footer = """          <p>{provenanceSentence(spec)}</p>"""
assert src.count(old_footer) == 1, "footer block not unique"
src = src.replace(old_footer, new_footer, 1)

open(path, "w").write(src)
print("P-1 edits applied to temp copy")
PYEOF

# Generate the diff (prose header + git diff)
{
echo "WIRE-SPEC P-1: footer provenance reads spec.provenance (QA-TRUTH F-001)."
echo ""
echo "WHAT IT DOES"
echo "------------"
echo "src/app/sites/_shared/site-client.tsx: the provenance footer no longer"
echo "hardcodes \"(acceptance sequences 65-83)\". It renders spec.provenance."
echo "The parenthetical appears only when the spec carries an eventSequences"
echo "pair; absent data omits it. Golden route renders byte-identical."
echo ""
git diff --no-index --src-prefix=a/ --dst-prefix=b/ src/app/sites/_shared/site-client.tsx /tmp/site-client-new.tsx | tail -n +3
} > /mnt/c/Users/nolan/transfer/sites-wire-p1-footer-provenance.patch
echo "P-1 patch written"

echo ""
echo "=== P-2: renderer.tsx ==="
cp src/fyd/components/renderer.tsx /tmp/renderer-new.tsx
python3 << 'PYEOF'
path = "/tmp/renderer-new.tsx"
src = open(path).read()

# Change both Rights basis steps from "observed" to "inferred"
# Location 1: multi-line push
old1 = """  if (media.rightsBasis) {
    steps.push({
      step: "Rights basis",
      detail: media.rightsBasis,
      state: "observed",
    });
  }"""
new1 = """  if (media.rightsBasis) {
    steps.push({
      step: "Rights basis",
      detail: media.rightsBasis,
      // Policy inference, not an observation: classifyRights is a URL
      // heuristic with no authorization evidence (QA-TRUTH F-002).
      state: "inferred",
    });
  }"""
assert src.count(old1) == 1, "rights block 1 not unique"
src = src.replace(old1, new1, 1)

# Location 2: single-line push
old2 = """    steps.push({ step: "Rights basis", detail: media.rightsBasis, state: "observed" });"""
new2 = """    // Policy inference, not an observation: classifyRights is a URL
    // heuristic with no authorization evidence (QA-TRUTH F-002).
    steps.push({ step: "Rights basis", detail: media.rightsBasis, state: "inferred" });"""
assert src.count(old2) == 1, "rights block 2 not unique"
src = src.replace(old2, new2, 1)

open(path, "w").write(src)
print("P-2 edits applied to temp copy")
PYEOF

{
echo "WIRE-SPEC P-2: rights-basis step labeled \"inferred\", not \"observed\" (QA-TRUTH F-002)."
echo ""
echo "WHAT IT DOES"
echo "------------"
echo "src/fyd/components/renderer.tsx: the Rights basis EvidenceStep is pushed"
echo "with state \"inferred\" instead of \"observed\". Golden route renders no"
echo "rights step (no media), so zero DOM change on golden."
echo ""
git diff --no-index --src-prefix=a/ --dst-prefix=b/ src/fyd/components/renderer.tsx /tmp/renderer-new.tsx | tail -n +3
} > /mnt/c/Users/nolan/transfer/sites-wire-p2-rights-inferred.patch
echo "P-2 patch written"

echo ""
echo "=== checking P-1 ==="
git apply --check /mnt/c/Users/nolan/transfer/sites-wire-p1-footer-provenance.patch && echo "P-1 PASS" || echo "P-1 FAIL"
echo "=== checking P-2 ==="
git apply --check /mnt/c/Users/nolan/transfer/sites-wire-p2-rights-inferred.patch && echo "P-2 PASS" || echo "P-2 FAIL"

# Copy the generated patches back to the workspace via transfer dir listing
ls -la /mnt/c/Users/nolan/transfer/sites-wire-p*.patch

#!/usr/bin/env python3
"""PING -> OpenShell policy generator.

PING declares what a worker needs; OpenShell enforces it. This module
turns a worker's declared capabilities into an OpenShell candidate policy
YAML, ready for `openshell-prover check --boundary <boundary>`.

Design rules (Nolan, binding):
- PING is the authority. OpenShell is the enforcement fence. This
  generator is a TRANSLATOR, not an authority: it cannot grant anything
  the capability declaration doesn't ask for, and the prover verifies
  containment in the operator boundary.
- Deny by default: the generator emits ONLY what is declared. No
  implicit network, no implicit binaries, no credential material.
- Deterministic: same capability declaration -> same YAML bytes
  (sorted keys, fixed ordering). The policy is a build artifact.

Usage:
    from ping_policy_gen import generate_policy
    yaml_text = generate_policy(WorkerCapabilities(...))
"""
from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class NetworkEndpoint:
    host: str
    port: int = 443


@dataclass(frozen=True)
class WorkerCapabilities:
    """What a PING worker declares it needs. PING authority decides;
    this declaration is the input, not the permission."""
    worker_name: str
    # Network: named groups of endpoints. Least privilege: only list
    # what the worker's pass definition requires.
    network_groups: tuple = ()  # tuple of (group_name, tuple[NetworkEndpoint])
    # Filesystem.
    read_only: tuple = ("/bin", "/usr", "/lib", "/proc", "/dev/urandom",
                        "/app", "/etc", "/var/log")
    read_write: tuple = ("/tmp", "/sandbox")
    # include_workdir is FALSE by default: the prover cannot verify a
    # policy whose filesystem authority depends on an unresolved deploy-
    # time workdir (proven 2026-10-03: honest policy went "unsupported"
    # with it, "within_boundary" without). Enable at deploy time only
    # with a resolved absolute workdir, and re-prove.
    include_workdir: bool = False
    # Process.
    binaries: tuple = ("/usr/bin/node", "/usr/bin/python3")
    run_as_user: str = "1500"
    run_as_group: str = "1500"
    landlock_compatibility: str = "best_effort"


def _yaml_str(s: str) -> str:
    return '"%s"' % s.replace("\\", "\\\\").replace('"', '\\"')


def generate_policy(caps: WorkerCapabilities) -> str:
    """Generate deterministic OpenShell candidate policy YAML."""
    L = []
    L.append(f"# OpenShell candidate policy for PING worker: {caps.worker_name}")
    L.append("# GENERATED by ping_policy_gen.py -- do not hand-edit.")
    L.append("# PING declares; OpenShell enforces. Prover must confirm")
    L.append("# containment in the operator boundary before use.")
    L.append("")
    L.append("version: 1")
    L.append("")
    L.append("filesystem_policy:")
    # Omit include_workdir when false (prover default); emit only when true.
    if caps.include_workdir:
        L.append("  include_workdir: true")
    L.append("  read_only: [%s]" % ", ".join(caps.read_only))
    L.append("  read_write: [%s]" % ", ".join(caps.read_write))
    L.append("")
    L.append("landlock:")
    L.append(f"  compatibility: {caps.landlock_compatibility}")
    L.append("")
    L.append("process:")
    L.append(f"  run_as_user: {_yaml_str(caps.run_as_user)}")
    L.append(f"  run_as_group: {_yaml_str(caps.run_as_group)}")
    L.append("")
    L.append("network_policies:")
    for group_name, endpoints in sorted(caps.network_groups):
        L.append(f"  {group_name}:")
        L.append(f"    name: {group_name}-platform")
        L.append("    endpoints:")
        for ep in sorted(endpoints, key=lambda e: (e.host, e.port)):
            L.append(f"      - host: {ep.host}")
            L.append(f"        port: {ep.port}")
        L.append("    binaries:")
        for b in sorted(caps.binaries):
            L.append(f"      - {{ path: {b} }}")
    L.append("")
    return "\n".join(L)


# The LinkedIn engagement worker, from the standing 2-hour pass definition.
LINKEDIN_WORKER = WorkerCapabilities(
    worker_name="ping-linkedin-worker",
    network_groups=(
        ("linkedin", (NetworkEndpoint("www.linkedin.com", 443),)),
    ),
)


if __name__ == "__main__":
    print(generate_policy(LINKEDIN_WORKER), end="")

/**
 * ASK FYD GOLD-SET BASELINE.
 *
 * FALSIFIABILITY QUESTIONNAIRE
 * WHAT INVARIANT? The deterministic Ask FYD path (object graph + evidence
 *   index + lexical/structural retrieval) answers supported questions with
 *   evidence-cited claims, and refuses honestly (no asserted facts) when
 *   the record has no supporting evidence.
 * WHO OWNS IT? src/lib/ping/ask-composer.ts (composeAnswer/buildAskContext)
 *   and src/fyd/ask/context-projection.ts (FYD-010 viewer projection).
 *   This suite owns only the gold set + harness; it must never reimplement
 *   the composer.
 * HOW CAN IT FAIL? A composer branch asserts a claim with no evidenceRef;
 *   a variant leak (private object named in an answer); a forbidden claim
 *   substring in answer text; required evidence uncited.
 * WHAT ATTACK DISPROVES IT? The 32-question gold set (8 epistemic
 *   categories x 2 real websites) + synthetic privacy/conflict/owner
 *   variants, each with required/allowed evidence, forbidden claims, and
 *   expected epistemic status.
 * WHAT EVIDENCE PROVES IT? Per-question metrics JSON (committed at
 *   metrics/baseline-metrics.json): requiredRecall, supportRate,
 *   forbiddenHits, refused, latencyMs.
 * CAN IT BE REPLAYED? Yes: deterministic composer; gold-set.json is
 *   generated by gold-set-gen.py (committed); same fixture + same variant
 *   => same metrics bytes modulo latencyMs.
 * DOES THE FAILURE BECOME PERMANENT REGRESSION KNOWLEDGE? Yes: each
 *   question has a stable ASK-NNN id; a regression names the question id,
 *   the category, and the violated expectation.
 * WHY CAN EXISTING RUNNER + LIBRARY + EXISTING PING AUTHORITY NOT EXPRESS
 *   THIS? The existing suites test the composer in isolation per area; none
 *   drives the full production path (fixture graph -> FYD-010 projection ->
 *   evidence index -> composer) against a fixed adversarial question set
 *   with scored epistemic expectations. The gold set is the new semantic
 *   owner for Ask FYD answer truth; the harness wires existing owners.
 *
 * JEV budget for this lane: <= 60 live calls for the initial shadow run
 * (jev-shadow.mjs). This suite makes ZERO JEV calls.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { loadGoldSet, runGoldQuestion, scoreRun } from "./baseline";

const METRICS_DIR = join(__dirname, "metrics");

/**
 * KNOWN PRODUCT GAPS (falsification ledger). These question ids are
 * excluded from the green-path assertions below because the CURRENT
 * product behavior violates the gold-set requirement. Each gap is
 * documented and re-asserted in known-gaps.test.ts (which is EXPECTED
 * to fail until the product is fixed). The exclusions are explicit so
 * a green run here never means "no gaps".
 *
 * AG-001 (ASK-014): coverage branch lexical gap. "What do you NOT know?"
 *   does not trigger the asksCoverage branch (regex needs contiguous
 *   "do not"); the composer answers with a profile blurb instead of an
 *   evidence-bound limitations answer.
 * AG-002 (ASK-030): owner object-hide does not reach the Ask FYD answer
 *   path. FieldVisibilityDecision hide on a service's title/description
 *   drops fields[] entries only; the composer lists services by the
 *   top-level object title, so the hidden service still appears. The
 *   customize lane's hide_object intent is presentation-layer only, and
 *   the owner store's hiddenServices (set-service-visibility) is never
 *   consulted by buildAskFydContext/composeAskFyd.
 * AG-003 (ASK-018): branch-inconsistent conflict acknowledgment. The
 *   coverage branch describes conflicted facets as "being verified", but
 *   a direct question about a conflicted non-contact field (hours)
 *   answers "No hours are on record" — absence stated as fact while the
 *   value is disputed, not absent.
 * AG-004 (ASK-020): conflict suppression is field-literal, not
 *   semantic-fact-wide. The conflict names the location object's
 *   address_locality, but the composer states the same address fact from
 *   the business object's locality field. (FYD-Q2's hide path has the
 *   address-family treatment; the FYD-Q1 conflict path does not.)
 */
export const KNOWN_GAPS: Record<string, string> = {
  "ASK-014": "AG-001",
  "ASK-030": "AG-002",
  "ASK-018": "AG-003",
  "ASK-020": "AG-004",
};

describe("Ask FYD gold-set baseline (deterministic, no JEV)", () => {
  const records = loadGoldSet();

  test("gold set shape: 32 questions, 8 categories, stable ids", () => {
    expect(records).toHaveLength(32);
    const cats = new Set(records.map((r) => r.category));
    expect([...cats].sort()).toEqual([
      "ambiguous",
      "contradicted",
      "directly-supported",
      "multi-object",
      "owner-corrected",
      "privacy-hidden",
      "relationship-dependent",
      "unsupported",
    ]);
    expect(new Set(records.map((r) => r.id)).size).toBe(32);
  });

  test("baseline run: metrics recorded for every question", () => {
    const rows = records.map((rec) => {
      const run = runGoldQuestion(rec);
      const score = scoreRun(rec, run);
      return {
        id: rec.id,
        question: rec.question,
        category: rec.category,
        variant: rec.variant,
        business: rec.business,
        expectedEpistemic: rec.expectedEpistemic,
        candidateEvidenceCount: run.candidateEvidenceIds.length,
        claimClassifications: run.claimClassifications,
        answerPreview: run.answer.answer.slice(0, 400),
        partial: run.answer.partial,
        unknowns: run.answer.unknowns,
        score: {
          requiredRecall: score.requiredRecall,
          citedRequired: score.citedRequired,
          citedOutsideAllowed: score.citedOutsideAllowed,
          forbiddenHits: score.forbiddenHits,
          claimsTotal: score.claimsTotal,
          claimsWithEvidence: score.claimsWithEvidence,
          supportRate: score.supportRate,
          refused: score.refused,
          conflictAcknowledged: score.conflictAcknowledged,
        },
        latencyMs: run.latencyMs,
      };
    });

    mkdirSync(METRICS_DIR, { recursive: true });
    writeFileSync(
      join(METRICS_DIR, "baseline-metrics.json"),
      JSON.stringify(
        {
          generated: new Date().toISOString(),
          suite: "ask-fyd-baseline",
          jevCalls: 0,
          rows,
        },
        null,
        2,
      ),
    );

    // Aggregate sanity: every run completes and records.
    expect(rows).toHaveLength(32);
    const totalLatency = rows.reduce((a, r) => a + r.latencyMs, 0);
    // Deterministic composer on fixture graphs: the whole gold set must run
    // in well under a second per question on average.
    expect(totalLatency / rows.length).toBeLessThan(1000);
  });

  test("no forbidden claim appears in any answer", () => {
    const violations: string[] = [];
    for (const rec of records) {
      if (KNOWN_GAPS[rec.id]) continue; // gap ledger owns these; see known-gaps.test.ts
      const run = runGoldQuestion(rec);
      const score = scoreRun(rec, run);
      for (const hit of score.forbiddenHits) {
        violations.push(`${rec.id}: forbidden claim present: ${hit}`);
      }
    }
    expect(violations).toEqual([]);
  });

  test("every asserted factual claim carries evidence", () => {
    // supportRate == 1.0 means every claimClassification has >= 1 evidenceRefId.
    const bad: string[] = [];
    for (const rec of records) {
      const run = runGoldQuestion(rec);
      const score = scoreRun(rec, run);
      if (score.supportRate < 1.0) {
        bad.push(
          `${rec.id}: supportRate=${score.supportRate} claims=${score.claimsTotal}`,
        );
      }
    }
    expect(bad).toEqual([]);
  });

  test("unsupported questions are refused or explicitly based, never fabricated", () => {
    const unsupported = records.filter((r) => r.category === "unsupported");
    expect(unsupported.length).toBe(4);
    const bad: string[] = [];
    for (const rec of unsupported) {
      if (KNOWN_GAPS[rec.id]) continue; // AG-001 ledger
      const run = runGoldQuestion(rec);
      const score = scoreRun(rec, run);
      if (score.refused) continue;
      // Non-refusal is allowed ONLY when every claim is evidenced and the
      // answer states its uncertainty basis explicitly (e.g. the ASK-013
      // INFERENCE negative: "nothing in the site record mentions it").
      const honest =
        score.supportRate === 1.0 &&
        /nothing in the site record|not (?:on|in) (?:the )?record|no evidence/i.test(
          run.answer.answer,
        );
      if (!honest) bad.push(`${rec.id}: unsupported answer without explicit basis`);
    }
    expect(bad).toEqual([]);
  });

  test("contradicted questions acknowledge the conflict (FYD-Q1)", () => {
    const contradicted = records.filter((r) => r.category === "contradicted");
    expect(contradicted.length).toBe(4);
    const bad: string[] = [];
    for (const rec of contradicted) {
      if (rec.id in KNOWN_GAPS) continue; // red by design in the ledger
      const run = runGoldQuestion(rec);
      const score = scoreRun(rec, run);
      // Never state a disputed value as certain: scoreRun auto-adds the
      // variant's canonical and conflicting values to the forbidden set.
      for (const hit of score.forbiddenHits) {
        bad.push(`${rec.id}: forbidden claim present: ${hit}`);
      }
      // ASK-017 exercises the FYD-Q1 locked copy on the contact path.
      if (rec.id === "ASK-017" && !score.conflictAcknowledged) {
        bad.push(`${rec.id}: conflict not acknowledged in answer`);
      }
      // ASK-019 (description conflict): no locked copy exists for
      // non-contact fields; the requirement is honest fallback without
      // stating either description, and full evidence support.
      if (rec.id === "ASK-019" && score.supportRate < 1.0) {
        bad.push(`${rec.id}: unevidenced claim in conflict answer`);
      }
    }
    expect(bad).toEqual([]);
  });

  test("first acceptance: services question cites every service object", () => {
    const rec = records.find((r) => r.id === "ASK-001");
    expect(rec).toBeDefined();
    const run = runGoldQuestion(rec!);
    const score = scoreRun(rec!, run);
    // All four Coppersmith service objects must be cited by the answer's claims.
    expect(score.requiredRecall).toBe(1.0);
    expect(score.citedRequired).toHaveLength(4);
    // Every claim in the first-acceptance answer carries the full chain:
    // CLAIM -> evidenceRefIds -> (evidence detail carries SOURCE + OBSERVED AT
    // via provenance; classification carries DIRECT/DERIVED/INFERRED class).
    for (const c of run.claimClassifications) {
      expect(c.evidenceRefIds.length).toBeGreaterThan(0);
      expect(typeof c.classification).toBe("string");
      expect(c.classification.length).toBeGreaterThan(0);
    }
  });

  test("owner correction: corrected value is on-record, source value only as superseded", () => {
    // ASK-029 (phone) and ASK-031 (email) go through the REAL owner store
    // (applyOwnerCommand with a temp FYD_OWNER_DIR) and the real overlay
    // (applyOwnerFieldCorrections). The product contract is SOURCE SAYS X /
    // OWNER SAYS Y: the corrected value is presented as on-record, and the
    // stale website value may appear only explicitly marked as superseded.
    const cases: Array<{ id: string; ownerValue: string; stalePhrasing: RegExp }> = [
      { id: "ASK-029", ownerValue: "(970) 555-9999", stalePhrasing: /Phone on record: 970-245-3869/ },
      { id: "ASK-031", ownerValue: "hello@happyplacecarpentry.com", stalePhrasing: /Email on record: taylor@happyplacecarpentry\.com/ },
    ];
    for (const { id, ownerValue, stalePhrasing } of cases) {
      const rec = records.find((r) => r.id === id)!;
      const run = runGoldQuestion(rec);
      const score = scoreRun(rec, run);
      const answer = run.answer.answer;
      expect(answer).toContain(ownerValue);
      // Every claim in the corrected answer carries evidence
      // (the correction itself is evidence-backed: owner_value ref).
      expect(score.supportRate).toBe(1.0);
      // The stale value is never presented as the current on-record value.
      expect(answer).not.toMatch(stalePhrasing);
      // And the correction is attributed to the owner, not the website.
      expect(answer).toMatch(/owner corrected/i);
    }
  });
});

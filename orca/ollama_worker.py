"""
ORCA seam falsification — Agent #2 (local Ollama) worker adapter (2026-10-02).

Identical contract to mission2.call_model(model, prompt, max_tokens):
    call_ollama(prompt, max_tokens=2000) -> (output_text, attempts_used)

Differences from call_model:
  - execution target is a LOCAL model on the Pig (Ollama in WSL), reached
    ONLY through the existing proven transport ~/workspace/pig-fb/pigwsl-exec.sh
    (ssh hop -> wsl -d Ubuntu bash). No network bridge, no remote provider.
  - Ollama HTTP API (/api/generate, stream=false) via curl on the Pig side.
    The bash script is piped through pigwsl-exec's STDIN (never as argv), so
    the payload needs no shell quoting at all: JSON is generated by Python
    and embedded in a heredoc. This also sidesteps pigwsl-exec's stripping of
    literal single-quoted substrings (2026-09-29 lesson): the transmitted
    script contains zero single quotes.
  - the worker boundary never sees mission state, writes no events, and is
    invisible to mission semantics (per SEAM_TRACE.md).
  - the independent verifier (epistemic gate) still stands between the worker
    claim and VERIFIED_SUCCESS: WORKER SAYS SUCCESS != VERIFIED RESULT.

Zero changes to mission2.py, model_router.py, dispatch.py, or any
scheduler/state-machine code. This file only CONSUMES the existing seam.
The router is not consulted: the local Ollama model is not in its pool.

max_tokens is accepted for contract parity; it maps to Ollama's num_predict.

Empty string is returned on total failure (transport unreachable, non-zero
exit, unparseable response, empty generation, or timeout on every attempt).
A dead local model is an honest empty result, never a simulated worker.
"""

import json
import subprocess

PIGWSL_EXEC = "/home/hatch/workspace/pig-fb/pigwsl-exec.sh"
OLLAMA_URL = "http://127.0.0.1:11434/api/generate"
MODEL = "qwen2.5-coder:1.5b"
_MAX_ATTEMPTS = 3
_CURL_TIMEOUT_SEC = 300  # model-load latency + small-model generation


def _build_script(payload_json):
    """Bash script for the Pig side. No single quotes anywhere in the
    transmitted text (pigwsl-exec strips them); JSON travels in a heredoc."""
    return (
        "curl -s --max-time " + str(_CURL_TIMEOUT_SEC)
        + " -X POST " + OLLAMA_URL
        + " -H Content-Type:application/json -d @- <<OLLA_EOF\n"
        + payload_json
        + "\nOLLA_EOF\n"
    )


def _extract_response(stdout):
    """Parse the /api/generate (stream=false) JSON envelope and return the
    model's text. Raises ValueError on any malformed envelope."""
    data = json.loads(stdout)
    text = data.get("response", "")
    if not isinstance(text, str):
        raise ValueError("ollama response field is not a string")
    text = text.strip()
    # Strip code fences the same way mission2.call_model does
    if text.startswith("```"):
        text = "\n".join(
            l for l in text.split("\n") if not l.strip().startswith("```")
        ).strip()
    return text


def call_ollama(prompt, max_tokens=2000):  # noqa: ARG001 - contract parity
    """Returns (output_text, attempts_used). Empty string on total failure."""
    payload = json.dumps({
        "model": MODEL,
        "prompt": prompt,
        "stream": False,
        "options": {"num_predict": max_tokens},
    })
    script = _build_script(payload)
    for attempt in range(1, _MAX_ATTEMPTS + 1):
        try:
            r = subprocess.run(
                [PIGWSL_EXEC],
                input=script,
                capture_output=True, text=True,
                timeout=_CURL_TIMEOUT_SEC + 60)
            if r.returncode != 0:
                continue
            try:
                text = _extract_response(r.stdout or "")
            except ValueError:
                continue
            if text and text != "None":
                return text, attempt
        except subprocess.TimeoutExpired:
            continue
        except Exception:
            continue
    return "", _MAX_ATTEMPTS


if __name__ == "__main__":
    # Self-test: trivial prompt against the real local model (not simulated).
    text, attempts = call_ollama("Reply with the single word: alive",
                                 max_tokens=10)
    print(f"attempts_used={attempts}")
    print(f"response={text!r}")
    assert "alive" in text.lower(), f"self-test FAILED: {text!r}"
    print("SELF-TEST PASS")

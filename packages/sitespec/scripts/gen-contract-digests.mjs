#!/usr/bin/env node
/**
 * Generate src/contract-digests.ts: pins the render contract.
 *
 * QUERY_CATALOG_DIGEST covers the section query seam (query.ts), the
 * component catalog (components.ts), and the schema roles they share
 * (schema-roles.ts): any query-resolution or catalog change rotates it.
 * THEME_TOKENS_DIGEST covers the theme token contracts (types.ts):
 * any token-shape change rotates it.
 *
 * render-model.ts derives RENDERER_VERSION and DESIGN_TOKEN_VERSION from
 * these digests, so a stale pin is a contract violation, not silent
 * drift. Regenerate with: node scripts/gen-contract-digests.mjs
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const sha = (p) =>
  createHash("sha256").update(readFileSync(join(root, p))).digest("hex");

const QUERY_CATALOG_DIGEST = sha("src/query.ts") &&
  createHash("sha256")
    .update(readFileSync(join(root, "src/query.ts")))
    .update(readFileSync(join(root, "src/components.ts")))
    .update(readFileSync(join(root, "src/schema-roles.ts")))
    .digest("hex");
const THEME_TOKENS_DIGEST = sha("src/types.ts");

const out = `/**
 * GENERATED by scripts/gen-contract-digests.mjs. Do not edit by hand.
 *
 * Semantic contract digests. These pin the render contract:
 * - QUERY_CATALOG_DIGEST covers the section query seam (src/query.ts),
 *   the component catalog (src/components.ts), and the schema roles
 *   (src/schema-roles.ts); any query-resolution or catalog change
 *   rotates it.
 * - THEME_TOKENS_DIGEST covers FYDThemeTokens and its token interfaces
 *   (src/types.ts); any token-shape change rotates it.
 *
 * render-model.ts derives RENDERER_VERSION and DESIGN_TOKEN_VERSION from
 * these digests, so a stale pin is a contract violation, not a silent
 * drift. Regenerate with: node scripts/gen-contract-digests.mjs
 */
export const QUERY_CATALOG_DIGEST = "${QUERY_CATALOG_DIGEST}";
export const THEME_TOKENS_DIGEST = "${THEME_TOKENS_DIGEST}";
export const CONTRACT_DIGEST_SOURCES = {
  query: "src/query.ts",
  components: "src/components.ts",
  schemaRoles: "src/schema-roles.ts",
  types: "src/types.ts",
} as const;
`;

writeFileSync(join(root, "src/contract-digests.ts"), out);
console.log("wrote src/contract-digests.ts");
console.log("QUERY_CATALOG_DIGEST", QUERY_CATALOG_DIGEST);
console.log("THEME_TOKENS_DIGEST ", THEME_TOKENS_DIGEST);

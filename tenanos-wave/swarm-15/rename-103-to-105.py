import json
from datetime import datetime, timezone

now = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
with open("/home/hatch/workspace/tenanos-wave/STATE.json") as f:
    s = json.load(f)

ids = [p["id"] for p in s["proposals"]]
assert "P-20260923-105" not in ids, "105 taken"
assert "P-20260923-103" in ids, "103 entry missing"

for p in s["proposals"]:
    if p["id"] == "P-20260923-103":
        p["id"] = "P-20260923-105"
        p["diff_ref"] = "diffs/P-20260923-105.diff"
        p["notes"] += (" RENAME 03:2xZ: entry re-issued as P-20260923-105 because diffs/P-20260923-103.diff "
                       "was overwritten at 03:19:57Z by an unregistered swarm-02 artifact (attempt-fencing test, "
                       "no STATE.json entry); D1 content regenerated byte-identical at diffs/P-20260923-105.diff. "
                       "Coordinator: swarm-02's file at diffs/P-20260923-103.diff is preserved but has no STATE entry.")
        p["updated_at"] = now
        break

s["updated_at"] = now
s["updated_by"] = "swarm-15"
with open("/home/hatch/workspace/tenanos-wave/STATE.json", "w") as f:
    json.dump(s, f, indent=2)

# verify
s2 = json.load(open("/home/hatch/workspace/tenanos-wave/STATE.json"))

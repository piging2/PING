print("105 present:", "P-20260923-105" in ids2, "| 103 present:", "P-20260923-103" in ids2)
for p in s2["proposals"]:
    if p["id"] in ("P-20260923-104", "P-20260923-105"):
        print(p["id"], p["swarm"], p["status"], p["diff_ref"])
